#!/usr/bin/env node
'use strict';

/**
 * sync-skills.js — scan C:/.skills/skills for SKILL.md folders (recursive),
 * junction the TOP-LEVEL ones into ~/.agents/skills, and regenerate
 * skills.json plus skills/INDEX.md with both top-level and nested skills.
 *
 * Junctions only cover top-level skills because folder names in the dest
 * dir must be unique; nested skills are indexed for search/suggest but
 * not junctioned.
 *
 * Usage:
 *   node sync-skills.js [--dry-run] [--verbose]
 *                       [--source <dir>] [--dest <dir>]
 *                       [--no-install] [--no-index]
 */

const fs = require('fs');
const path = require('path');
const os = require('os');
const { walkSkills } = require('./scan-skills.js');

function discoverTopLevelSkills(sourceDir) {
  if (!fs.existsSync(sourceDir)) {
    throw new Error('Skill source not found: ' + sourceDir);
  }
  const found = [];
  for (const entry of fs.readdirSync(sourceDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (entry.name.startsWith('.')) continue;
    const skillDir = path.join(sourceDir, entry.name);
    if (!fs.existsSync(path.join(skillDir, 'SKILL.md'))) continue;
    found.push({ name: entry.name, path: skillDir });
  }
  found.sort((a, b) => a.name.localeCompare(b.name));
  return found;
}

/**
 * Recursive scan for every SKILL.md under sourceDir. Returns
 * [{ id, name, path, depth, parentPack }] sorted by id.
 */
function discoverAllSkills(sourceDir) {
  if (!fs.existsSync(sourceDir)) {
    throw new Error('Skill source not found: ' + sourceDir);
  }
  const hits = walkSkills(sourceDir);
  const out = hits.map(h => {
    const relParts = h.relPath.split('/');
    return {
      id: h.relPath,
      name: path.basename(h.folderPath),
      path: h.folderPath,
      depth: h.depth,
      parentPack: relParts.length > 1 ? relParts[0] : null,
    };
  });
  out.sort((a, b) => a.id.localeCompare(b.id));
  return out;
}

function destExists(destPath) {
  try {
    fs.lstatSync(destPath);
    return true;
  } catch (err) {
    if (err && err.code === 'ENOENT') return false;
    throw err;
  }
}

function installMissing(skills, destDir, opts) {
  const dryRun = !!(opts && opts.dryRun);
  fs.mkdirSync(destDir, { recursive: true });
  const added = [];
  const skipped = [];
  const errors = [];
  const linkType = process.platform === 'win32' ? 'junction' : 'dir';

  for (const skill of skills) {
    const destPath = path.join(destDir, skill.name);
    if (destExists(destPath)) {
      skipped.push(skill.name);
      continue;
    }
    if (dryRun) {
      added.push(skill.name);
      continue;
    }
    try {
      fs.symlinkSync(skill.path, destPath, linkType);
      added.push(skill.name);
    } catch (err) {
      errors.push({ name: skill.name, error: err.message });
    }
  }
  return { added, skipped, errors };
}

function posixPath(p) {
  return String(p).replace(/\\/g, '/');
}

function writeSkillsJson(skills, outPath, source, nested) {
  nested = nested || [];
  const catalog = {
    generated: true,
    generatedAt: new Date().toISOString(),
    source: posixPath(source),
    rule: 'top-level directories containing SKILL.md (junctioned); nested SKILL.md indexed under nested[]',
    count: skills.length,
    entries: skills.map((s) => ({ name: s.name, path: posixPath(s.path) })),
    nestedCount: nested.length,
    nested: nested.map((s) => ({
      id: s.id,
      name: s.name,
      path: posixPath(s.path),
      parentPack: s.parentPack,
      depth: s.depth,
    })),
  };
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, JSON.stringify(catalog, null, 2) + '\n', 'utf8');
  return catalog;
}

function writeIndexMd(skills, outPath, nested) {
  nested = nested || [];
  const n = skills.length;
  let md = '# Skills Index\n\n';
  md += 'Generated by `bin/sync-skills.js`.\n\n';
  md += '## Top-level skills (' + n + ')\n\n';
  md += 'Folders directly under `skills/` containing `SKILL.md`. These are junctioned into `~/.agents/skills`.\n\n';
  for (const skill of skills) md += '- ' + skill.name + '\n';
  if (nested.length) {
    // Group nested skills by their pack for readability.
    const byPack = new Map();
    for (const s of nested) {
      const pack = s.parentPack || '(root)';
      if (!byPack.has(pack)) byPack.set(pack, []);
      byPack.get(pack).push(s);
    }
    md += '\n## Nested library skills (' + nested.length + ')\n\n';
    md += 'Indexed for search/suggest but not junctioned (names may collide with top-level or with each other). Reach them via their pack.\n\n';
    const packs = Array.from(byPack.keys()).sort();
    for (const pack of packs) {
      md += '### ' + pack + '\n\n';
      for (const s of byPack.get(pack)) md += '- ' + s.id + '\n';
      md += '\n';
    }
  }
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, md, 'utf8');
}

function defaultAgentsSkillsDir() {
  const home = process.env.USERPROFILE || process.env.HOME || os.homedir();
  return path.join(home, '.agents', 'skills');
}

function parseArgs(argv) {
  const out = {
    dryRun: false,
    verbose: false,
    source: null,
    dest: null,
    noInstall: false,
    noIndex: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--dry-run') out.dryRun = true;
    else if (arg === '--verbose') out.verbose = true;
    else if (arg === '--no-install') out.noInstall = true;
    else if (arg === '--no-index') out.noIndex = true;
    else if (arg === '--source' && argv[i + 1]) out.source = argv[++i];
    else if (arg === '--dest' && argv[i + 1]) out.dest = argv[++i];
    else if (arg === '--help' || arg === '-h') out.help = true;
  }
  return out;
}

function resolveSource(cliSource) {
  if (cliSource) return path.resolve(cliSource);
  const { resolve } = require('./path-resolver.js');
  return resolve({ startDir: __dirname }).skillsDir;
}

function main(argv) {
  const args = parseArgs(argv || process.argv.slice(2));
  if (args.help) {
    process.stdout.write(
      'Usage: node sync-skills.js [--dry-run] [--verbose] [--source DIR] [--dest DIR] [--no-install] [--no-index]\n'
    );
    return 0;
  }

  const source = resolveSource(args.source);
  const dest = args.dest ? path.resolve(args.dest) : defaultAgentsSkillsDir();
  const skills = discoverTopLevelSkills(source);
  const all = discoverAllSkills(source);
  const nested = all.filter(s => s.depth > 0);

  let install = { added: [], skipped: [], errors: [] };
  if (!args.noInstall) {
    install = installMissing(skills, dest, { dryRun: args.dryRun });
  }

  if (!args.noIndex && !args.dryRun) {
    const skillsRoot = path.dirname(source);
    writeSkillsJson(skills, path.join(skillsRoot, 'skills.json'), source, nested);
    writeIndexMd(skills, path.join(source, 'INDEX.md'), nested);
  }

  const added = install.added.length;
  const skipped = install.skipped.length;
  const errors = install.errors.length;
  const prefix = args.dryRun ? 'sync-skills (dry-run): ' : 'sync-skills: ';
  process.stdout.write(
    prefix +
      skills.length + ' top-level (' + nested.length + ' nested indexed), ' +
      added + ' added, ' +
      skipped + ' skipped, ' +
      errors + ' errors' +
      (args.noInstall ? ' (install skipped)' : '') +
      '\n'
  );

  if (args.verbose) {
    for (const name of install.added) process.stdout.write('  + ' + name + '\n');
    for (const err of install.errors) process.stdout.write('  ! ' + err.name + ': ' + err.error + '\n');
  }

  return errors > 0 ? 1 : 0;
}

module.exports = {
  discoverTopLevelSkills,
  discoverAllSkills,
  installMissing,
  writeSkillsJson,
  writeIndexMd,
  parseArgs,
  main,
};

if (require.main === module) {
  process.exit(main());
}
